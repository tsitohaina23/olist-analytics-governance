with checks as (
{%- for c in checks %}
    select
        '{{ c.id }}'                    as check_id,
        '{{ c.table }}'                 as table_name,
        '{{ c.dim }}'                   as quality_dimension,
        '{{ c.desc | replace("'", "''") }}' as description,
        ({{ c.failed }})                as failed_rows,
        ({{ c.total }})                 as total_rows,
        cast({{ c.threshold }} as double) as threshold_pct
    {%- if not loop.last %}
    union all
    {%- endif %}
{%- endfor %}
)

select
    check_id,
    table_name,
    quality_dimension,
    description,
    cast(failed_rows as bigint)                                             as failed_rows,
    cast(total_rows as bigint)                                              as total_rows,
    round(100.0 * failed_rows / nullif(total_rows, 0), 3)                   as failed_pct,
    threshold_pct,
    case when 100.0 * failed_rows / nullif(total_rows, 0) <= threshold_pct
         then 'conforme' else 'hors seuil' end                              as status
from checks
order by check_id
